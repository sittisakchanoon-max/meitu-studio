export type FilterCategory =
  | 'favorites'
  | 'featured'
  | 'new'
  | 'basic'
  | 'flash'
  | 'sweet'
  | 'korean'
  | 'film'
  | 'foodie'
  | 'bw';

export interface FilterRecipe {
  id: string;
  nameTh: string;
  nameEn: string;
  category: Exclude<FilterCategory, 'favorites'>;
  featured?: boolean;
  hotBadge?: boolean;
  swatch: [string, string];
  exposure?: number;      // -0.4..0.4
  contrast?: number;      // -0.5..0.6
  saturation?: number;    // -1..0.8
  warmth?: number;        // -0.5..0.5
  tint?: number;          // -0.4..0.4
  fade?: number;          // 0..0.35
  shadowTint?: [number, number, number];
  highlightTint?: [number, number, number];
  skinGlow?: number;      // 0..0.4
  vignette?: number;      // 0..0.6
  grain?: number;         // 0..0.4
  grayscale?: number;     // 0..1
  sepia?: number;         // 0..1
}

