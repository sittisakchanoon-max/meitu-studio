export type FilterCategory =
  | 'all'
  | 'natural'
  | 'film'
  | 'sweet'
  | 'korean'
  | 'japanese'
  | 'foodie'
  | 'vintage'
  | 'bw'
  | 'cinematic';

export interface FilterRecipe {
  id: string;
  nameTh: string;
  nameEn: string;
  category: Exclude<FilterCategory, 'all'>;
  swatch: [string, string];
  // Color grading parameters
  exposure?: number;      // -0.4..0.4
  contrast?: number;      // -0.5..0.6
  saturation?: number;    // -1..0.8
  warmth?: number;        // -0.5..0.5
  tint?: number;          // -0.4..0.4 (positive = pink/magenta, negative = green)
  fade?: number;          // 0..0.35 (lifts blacks)
  shadowTint?: [number, number, number];    // RGB additive lift in shadows (-40..40)
  highlightTint?: [number, number, number]; // RGB additive lift in highlights (-40..40)
  skinGlow?: number;      // 0..0.4 soft dreamy glow
  vignette?: number;      // 0..0.6
  grain?: number;         // 0..0.4
  grayscale?: number;     // 0..1
  sepia?: number;         // 0..1
}

